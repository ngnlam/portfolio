"""Builds the leo_ logo from the Bricolage Grotesque font the site already ships.

Writes:
  src/data/logo.ts           outlined "leo" paths and the cursor box, used by Logo.astro
  public/favicon.svg         favicon: an l and a yellow cursor on a graphite tile
  scripts/logo/out/*.svg     wordmark and mark files for use outside the site

Run locally (needs: pip install fonttools brotli uharfbuzz):
  python3 scripts/logo/build-logo.py
Then: node scripts/og/render-og.cjs --icons
"""
import io
import json
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
FONT = ROOT / 'node_modules/@fontsource-variable/bricolage-grotesque/files/bricolage-grotesque-latin-standard-normal.woff2'
OUT = ROOT / 'scripts/logo/out'

GRAPHITE, CREAM, SUN = '#1F2226', '#FFF8EC', '#FFC93C'

# Design values, in font units (1000 per em). Default instance is opsz 96, wght 800.
TRACKING = -35        # letter-spacing -0.035em, same as the canvas
CURSOR_GAP = 50       # space before the cursor
CURSOR_W, CURSOR_H = 420, 150
CURSOR_STROKE = 28
CURSOR_RX = 22

font = TTFont(str(FONT))
buf = io.BytesIO()
font.flavor = None
font.save(buf)
data = buf.getvalue()
font = TTFont(io.BytesIO(data))
glyphset = font.getGlyphSet()

blob = hb.Blob(data)
face = hb.Face(blob)
hbfont = hb.Font(face)
text = 'leo'
b = hb.Buffer()
b.add_str(text)
b.guess_segment_properties()
hb.shape(hbfont, b, {'kern': True, 'liga': False})

order = font.getGlyphOrder()
pen = SVGPathPen(glyphset)
bounds = BoundsPen(glyphset)
x = 0
for info, pos in zip(b.glyph_infos, b.glyph_positions):
    name = order[info.codepoint]
    # Flip y so the baseline sits at y = 0 and up is negative.
    glyphset[name].draw(TransformPen(pen, (1, 0, 0, -1, x + pos.x_offset, -pos.y_offset)))
    glyphset[name].draw(TransformPen(bounds, (1, 0, 0, -1, x + pos.x_offset, -pos.y_offset)))
    x += pos.x_advance + TRACKING

xmin, ymin, xmax, ymax = bounds.bounds   # ymin is the top (negative), ymax the overshoot below the baseline
cx = x + CURSOR_GAP
cursor = {
    'x': round(cx + CURSOR_STROKE / 2, 1),
    'y': round(-CURSOR_H + CURSOR_STROKE / 2, 1),
    'w': CURSOR_W - CURSOR_STROKE,
    'h': CURSOR_H - CURSOR_STROKE,
    'rx': CURSOR_RX,
    'stroke': CURSOR_STROKE,
}
pad = CURSOR_STROKE / 2
vb_x = round(xmin - pad)
vb_y = round(ymin - pad)
vb_w = round(cx + CURSOR_W + pad - vb_x)
vb_h = round(max(ymax, 0) + pad - vb_y)
viewbox = f'{vb_x} {vb_y} {vb_w} {vb_h}'
letters = pen.getCommands()

(ROOT / 'src/data/logo.ts').write_text(
    '// Generated by scripts/logo/build-logo.py from Bricolage Grotesque (opsz 96, wght 800).\n'
    '// Do not edit by hand: change the script and run it again.\n'
    f'export const LOGO = {json.dumps({"viewBox": viewbox, "width": vb_w, "height": vb_h, "letters": letters, "cursor": cursor}, indent=2)} as const;\n'
)


def wordmark(text_color, cursor_fill=SUN, cursor_stroke=GRAPHITE):
    c = cursor
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{viewbox}">'
        f'<path d="{letters}" fill="{text_color}"/>'
        f'<rect x="{c["x"]}" y="{c["y"]}" width="{c["w"]}" height="{c["h"]}" rx="{c["rx"]}" '
        f'fill="{cursor_fill}" stroke="{cursor_stroke}" stroke-width="{c["stroke"]}"/></svg>\n'
    )


# Favicon: the l stem and the cursor, which together read as an L.
# Every edge sits on a multiple of 4, so the shapes land on whole pixels at 16 and 32 px.
MARK_INNER = (
    f'<rect x="12" y="12" width="12" height="40" rx="2" fill="{CREAM}"/>'
    f'<rect x="28" y="40" width="24" height="12" rx="2" fill="{SUN}"/>'
)
favicon = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="14" fill="{GRAPHITE}"/>{MARK_INNER}</svg>\n'
square = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" fill="{GRAPHITE}"/>{MARK_INNER}</svg>\n'

(ROOT / 'public/favicon.svg').write_text(favicon)
OUT.mkdir(parents=True, exist_ok=True)
(OUT / 'leo-wordmark.svg').write_text(wordmark(GRAPHITE))
(OUT / 'leo-wordmark-on-dark.svg').write_text(wordmark(CREAM, SUN, GRAPHITE))
(OUT / 'leo-mark.svg').write_text(favicon)
(OUT / 'leo-mark-square.svg').write_text(square)
print('viewBox', viewbox, 'advance', x)
